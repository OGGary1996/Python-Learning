# 创建自定义模块
# 任何符合命名规则的 .py 文件都可以作为自定义模块。下面把计算逻辑和程序入口拆成两个文件：
# project/
# ├── prices.py
# └── 3-custom_module.py


# 模块顶层代码
# 模块中不属于函数或类的语句称为顶层代码。模块第一次被导入时，Python 会执行这些语句。
import prices
print(prices.price_cal(100))
# 输出中会先出现模块加载信息，这说明 import 不只是声明名称，还会执行模块顶层代码。


# 导入的副作用
# 模块导入时执行的可观察行为称为导入副作用，例如：
# - 打印内容
# - 发起网络请求
# - 读取大型文件
# - 修改全局状态
# - 启动线程或后台任务
# - 建立数据库连接
# 普通常量、函数定义和类定义适合放在模块顶层。昂贵操作和程序启动逻辑应放进函数，在真正需要时调用。


# __name__ 属性
# 每个模块都有 __name__ 属性，其值取决于模块的执行方式。
# 1. 直接运行模块，此时模块的 __name__ 等于 __main__
# 2. 被其他模块调用，此时模块的 __name__ 等于被调用模块的名称


# 主程序守卫
# 主程序守卫用于区分“直接执行”和“被其他模块导入”：
def main():
    print("This is the main program.")
if __name__ == "__main__":
    main()
# 1. 如果条件成立，表示单独执行模块，则调用main()
# 2. 如果条件不成立，说明作为模块被调用，不执行main()
# 主程序守卫适合保护：
# - 命令行参数解析
# - 程序启动逻辑
# - 演示代码和简单自测
# - 文件、网络和数据库操作


# 与 Java 的程序入口对比：
# - Java 规定 public static void main(String[] args) 作为常见程序入口
# - Python 没有强制的入口函数，开发者通常约定使用 main()
# - Python 模块的顶层代码会在导入时执行
# - Java 类加载时可能执行静态字段初始化和静态初始化块，但不会因为类被引用就自动执行顶层方法